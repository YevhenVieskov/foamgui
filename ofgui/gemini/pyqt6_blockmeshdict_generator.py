    def add_patch(self):
        name = self.patch_name_input.text().strip()
        patch_type = self.patch_type_combo.currentText()

        if not self.blocks:
            QMessageBox.warning(self, "Input Error", "No blocks defined to assign a patch to.")
            return

        if self.patch_block_id_combo.currentIndex() == -1 or self.patch_block_id_combo.currentText() == "No blocks defined":
             QMessageBox.warning(self, "Input Error", "Please select a valid Block ID.")
             return

        try:
            block_id = int(self.patch_block_id_combo.currentText())
        except ValueError:
            QMessageBox.warning(self, "Input Error", "Invalid Block ID selected.")
            return

        face_label_full = self.patch_face_combo.currentText()
        face_label = face_label_full.split(" ")[0] # "west", "east", etc.

        if not name:
            QMessageBox.warning(self, "Input Error", "Patch name cannot be empty.")
            return

        # Find the block and its vertices
        target_block_data = next((b for b in self.blocks if b[0] == block_id), None)
        if not target_block_data:
            QMessageBox.warning(self, "Input Error", f"Block ID {block_id} not found.")
            return

        block_global_v_ids = target_block_data[1]

        # Local vertex indices for faces of a hex block
        # (Order for OpenFOAM: right-hand rule, normal pointing outwards)
        face_local_indices = {
            "west":   [0, 4, 7, 3],
            "east":   [1, 2, 6, 5],
            "south":  [0, 1, 5, 4],
            "north":  [3, 7, 6, 2], # Corrected from some online sources, OpenFOAM standard
            "bottom": [0, 3, 2, 1],
            "top":    [4, 5, 6, 7]
        }

        if face_label not in face_local_indices:
            QMessageBox.critical(self, "Internal Error", f"Unknown face label: {face_label}")
            return

        local_v = face_local_indices[face_label]
        # Map local block vertex indices to global vertex IDs
        face_global_v_ids = [block_global_v_ids[i] for i in local_v]

        self.patches.append([name, patch_type, block_id, face_label_full, face_global_v_ids])
        self.update_patches_table()
        self.patch_name_input.clear()
        self.statusBar().showMessage(f"Patch '{name}' added to block {block_id}, face {face_label}.")

    def delete_patch(self):
        selected_rows = self.patches_table.selectionModel().selectedRows()
        if not selected_rows:
            QMessageBox.warning(self, "Selection Error", "No patch selected for deletion.")
            return

        # Patches are identified by a combination of name, block_id, and face for deletion
        # as names are not unique across the entire patch list in OpenFOAM but within a boundary entry.
        # For simplicity in the GUI, we delete by row.

        indices_to_delete = sorted([r.row() for r in selected_rows], reverse=True)
        for row_index in indices_to_delete:
            deleted_patch_name = self.patches_table.item(row_index, 0).text()
            del self.patches[row_index] # Simple deletion by list index
            self.statusBar().showMessage(f"Patch '{deleted_patch_name}' (row {row_index+1}) deleted.")

        self.update_patches_table()


