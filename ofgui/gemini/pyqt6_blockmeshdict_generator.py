    def generate_blockmesh_dict(self):
        if not self.vertices:
            QMessageBox.warning(self, "Generation Error", "No vertices defined.")
            self.blockmesh_dict_preview.setText("")
            return
        if not self.blocks:
            QMessageBox.warning(self, "Generation Error", "No blocks defined.")
            self.blockmesh_dict_preview.setText("")
            return

        # Header
        content = []
        content.append("/*--------------------------------*- C++ -*----------------------------------*\\")
        content.append("| =========                 |                                                 |")
        content.append("| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |")
        content.append("|  \\\\    /   O peration     | Version:  v2312                                 |")
        content.append("|   \\\\  /    A nd           | Website:  www.OpenFOAM.com                      |")
        content.append("|    \\\\/     M anipulation  |                                                 |")
        content.append("\\*---------------------------------------------------------------------------*/")
        content.append("FoamFile")
        content.append("{")
        content.append("    version     2.0;")
        content.append("    format      ascii;")
        content.append("    class       dictionary;")
        content.append("    object      blockMeshDict;")
        content.append("}")
        content.append("// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //")
        content.append("")
        content.append("convertToMeters 1;") # TODO: Make this configurable
        content.append("")

        # Vertices
        content.append("vertices")
        content.append("(")
        # Sort vertices by ID for consistent output, though OpenFOAM doesn't strictly require it if IDs match array index
        sorted_vertices = sorted(self.vertices, key=lambda v: v[0])
        max_vertex_id = -1
        if sorted_vertices:
            max_vertex_id = sorted_vertices[-1][0]

        # Create a list of vertex coordinates, filling in gaps if any (though our GUI ensures contiguous IDs for now)
        vertex_coords_map = {v[0]: (v[1], v[2], v[3]) for v in sorted_vertices}
        for i in range(max_vertex_id + 1):
            if i in vertex_coords_map:
                x, y, z = vertex_coords_map[i]
                content.append(f"    ({x:.6f} {y:.6f} {z:.6f}) // {i}")
            else: # Should not happen with current GUI logic but good for robustness
                content.append(f"    (0 0 0) // Placeholder for missing vertex {i} - ERROR")


        content.append(");")
        content.append("")

        # Blocks
        content.append("blocks")
        content.append("(")
        for b_id, v_ids, cells, grading in self.blocks:
            v_ids_str = " ".join(map(str, v_ids))
            cells_str = " ".join(map(str, cells))
            grading_str = " ".join(map(str, grading))
            content.append(f"    hex ({v_ids_str}) ({cells_str}) simpleGrading ({grading_str}) // block {b_id}")
        content.append(");")
        content.append("")

        # Edges (empty for now)
        content.append("edges")
        content.append("(")
        content.append(");")
        content.append("")

        # Boundary
        content.append("boundary")
        content.append("(")
        # Group patches by name
        patches_by_name = {}
        for name, p_type, b_id, face_lbl, face_v_ids in self.patches:
            if name not in patches_by_name:
                patches_by_name[name] = {"type": p_type, "faces": []}
            # Ensure type consistency for same patch name
            elif patches_by_name[name]["type"] != p_type:
                 QMessageBox.warning(self, "Patch Warning", f"Patch '{name}' has inconsistent types defined. Using first encountered: '{patches_by_name[name]['type']}'.")

            face_v_ids_str = " ".join(map(str, face_v_ids))
            patches_by_name[name]["faces"].append(f"({face_v_ids_str}) // block {b_id} {face_lbl}")

        for name, data in patches_by_name.items():
            content.append(f"    {name}")
            content.append("    {")
            content.append(f"        type        {data['type']};")
            content.append("        faces")
            content.append("        (")
            for face_entry in data["faces"]:
                content.append(f"            {face_entry}")
            content.append("        );")
            content.append("    }")
        content.append(");")
        content.append("")

        # MergePatchPairs (empty for now)
        content.append("mergePatchPairs")
        content.append("(")
        content.append(");")
        content.append("")
        content.append("// ************************************************************************* //")

        self.blockmesh_dict_preview.setText("\n".join(content))
        self.statusBar().showMessage("blockMeshDict generated.")
        self.tabs.setCurrentIndex(3) # Switch to generate tab

    def save_blockmesh_dict_to_file(self):
        content = self.blockmesh_dict_preview.toPlainText()
        if not content:
            QMessageBox.warning(self, "Save Error", "No blockMeshDict content to save. Please generate it first.")
            return

        file_path, _ = QFileDialog.getSaveFileName(
            self,
            "Save blockMeshDict",
            "blockMeshDict",  # Default filename
            "All Files (*);;OpenFOAM Dictionary Files (blockMeshDict*)"
        )

        if file_path:
            try:
                with open(file_path, 'w') as f:
                    f.write(content)
                self.statusBar().showMessage(f"blockMeshDict saved to {file_path}")
            except Exception as e:
                QMessageBox.critical(self, "Save Error", f"Could not save file: {e}")
                self.statusBar().showMessage(f"Error saving file: {e}")


