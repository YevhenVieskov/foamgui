    def add_block(self):
        v_ids_str = self.block_vertices_input.text().split()
        cells_str = self.block_cells_input.text().split()
        grading_str = self.block_grading_input.text().split()

        if len(v_ids_str) != 8:
            QMessageBox.warning(self, "Input Error", "A block requires exactly 8 vertex IDs.")
            return
        if len(cells_str) != 3:
            QMessageBox.warning(self, "Input Error", "Cells require 3 values (nx ny nz).")
            return
        if len(grading_str) != 3:
            QMessageBox.warning(self, "Input Error", "Grading requires 3 values (gx gy gz).")
            return

        try:
            v_ids = [int(vid) for vid in v_ids_str]
            cells = [int(c) for c in cells_str]
            grading = [float(g) for g in grading_str]
        except ValueError:
            QMessageBox.warning(self, "Input Error", "Invalid format for IDs, cells, or grading.")
            return

        # Validate vertex IDs
        defined_vertex_ids = [v[0] for v in self.vertices]
        for vid in v_ids:
            if vid not in defined_vertex_ids:
                QMessageBox.warning(self, "Input Error", f"Vertex ID {vid} is not defined.")
                return

        if any(c <= 0 for c in cells):
            QMessageBox.warning(self, "Input Error", "Cell counts must be positive integers.")
            return

        block_id = self.block_id_counter
        self.blocks.append([block_id, v_ids, tuple(cells), tuple(grading)])
        self.block_id_counter += 1
        self.update_blocks_table()
        self.block_vertices_input.clear()
        self.block_cells_input.clear()
        self.block_grading_input.setText("1 1 1")
        self.statusBar().showMessage(f"Block {block_id} added.")


