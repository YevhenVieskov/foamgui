    def load_vertex_for_editing(self):
        edit_id = self.edit_vertex_id_input.value()
        if edit_id == -1:
            QMessageBox.information(self, "Info", "Select a Vertex ID to load.")
            return

        vertex_to_edit = None
        for v in self.vertices:
            if v[0] == edit_id:
                vertex_to_edit = v
                break

        if vertex_to_edit:
            self.vertex_x_input.setText(str(vertex_to_edit[1]))
            self.vertex_y_input.setText(str(vertex_to_edit[2]))
            self.vertex_z_input.setText(str(vertex_to_edit[3]))
