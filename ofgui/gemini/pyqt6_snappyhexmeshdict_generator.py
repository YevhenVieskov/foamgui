        content.append(f"    multiRegionFeatureSnap  {b(sc['multiRegionFeatureSnap'])};")
        content.append("}")
        content.append("")

        # AddLayersControls
        alc = self.add_layers_controls
        content.append("addLayersControls")
        content.append("{")
        content.append(f"    relativeSizes           {b(alc['relativeSizes'])};")
        content.append(f"    expansionRatio          {alc['expansionRatio']:.2f};")
        content.append(f"    finalLayerThickness     {alc['finalLayerThickness']:.3f};")
        content.append(f"    minThickness            {alc['minThickness']:.3f};")
        content.append(f"    nGrow                   {alc['nGrow']};")
        content.append(f"    featureAngle            {alc['featureAngle']:.1f};")
        content.append(f"    maxFaceThicknessRatio   {alc['maxFaceThicknessRatio']:.2f};")
        content.append(f"    nSmoothSurfaceNormals   {alc['nSmoothSurfaceNormals']};")
        content.append(f"    nSmoothThickness        {alc['nSmoothThickness']};")
        content.append(f"    slipFeatureAngle        {alc['slipFeatureAngle']:.1f};")
        content.append(f"    nBufferCellsNoExtrude   {alc['nBufferCellsNoExtrude']};")
        content.append(f"    nLayerIter              {alc['nLayerIter']};")
        content.append("")
        content.append("    layers")
        content.append("    {")
        for layer_patch in alc["layers"]:
            content.append(f"        \"{layer_patch['patchName']}\" // Ensure this patchName is correct (from geometry or region)")
            content.append("        {")
            content.append(f"            nSurfaceLayers {layer_patch['nSurfaceLayers']};")
            content.append("        }")
        content.append("    }")
        content.append("}")
        content.append("")

        # MeshQualityControls
        mqc = self.mesh_quality_controls
        content.append("meshQualityControls")
        content.append("{")
        content.append(f"    maxNonOrtho             {mqc['maxNonOrtho']:.1f};")
        content.append(f"    maxBoundarySkewness     {mqc['maxBoundarySkewness']:.1f};")
        content.append(f"    maxInternalSkewness     {mqc['maxInternalSkewness']:.1f};")
        content.append(f"    maxConcave              {mqc['maxConcave']:.1f};")
        content.append(f"    minVol                  {mqc['minVol']:.2e};")
        content.append(f"    minTetQuality           {mqc['minTetQuality']:.2e};")
        content.append(f"    minArea                 {mqc['minArea']:.1f};")
        content.append(f"    minTwist                {mqc['minTwist']:.3f};")
        content.append(f"    minDeterminant          {mqc['minDeterminant']:.4f};")
        content.append(f"    minFaceWeight           {mqc['minFaceWeight']:.3f};")
