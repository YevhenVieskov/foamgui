    def get_defined_geometry_names(self):
        return [g["name"] for g in self.geometries if g["name"]]

    def get_potential_patch_names(self):
        """Collects geometry names and regions as potential patch names."""
        names = set()
        for geo in self.geometries:
            if geo["name"]:
                names.add(geo["name"]) # The geometry itself can be a patch
            if geo["regions"]:
                # Assuming regions are comma-separated
                regions = [r.strip() for r in geo["regions"].split(',') if r.strip()]
                for region_name in regions:
                    # Often regions are named like "geomName.regionName" or just "regionName"
                    # For simplicity, we'll just add the region name.
                    # User needs to ensure these match how SHM interprets them.
                    names.add(region_name)
        return sorted(list(names)) if names else ["DefaultPatch"]


