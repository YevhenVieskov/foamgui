    def generate_shm_dict_content(self):
        """Generates the string content for snappyHexMeshDict."""
        # Helper for boolean to string
        def b(val): return "true" if val else "false"
        def format_list_of_strings(lst):
            if not lst: return ""
            return "\n    ".join(f'"{s}"' for s in lst)


        content = []
        content.append("/*--------------------------------*- C++ -*----------------------------------*\\")
        content.append("| =========                 |                                                 |")
        content.append("| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |")
        content.append("|  \\\\    /   O peration     | Version:  v2312 (example)                       |")
        content.append("|   \\\\  /    A nd           | Website:  www.OpenFOAM.com                      |")
        content.append("|    \\\\/     M anipulation  | Generated by PyQt SnappyHexMesh GUI             |")
        content.append("\\*---------------------------------------------------------------------------*/")
        content.append("FoamFile")
        content.append("{")
        content.append("    version     2.0;")
        content.append("    format      ascii;")
        content.append("    class       dictionary;")
        content.append("    object      snappyHexMeshDict;")
        content.append("}")
        content.append("// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //")
        content.append("")

        gs = self.general_settings
        content.append(f"castellatedMesh {b(gs['castellatedMesh'])};")
        content.append(f"snap            {b(gs['snap'])};")
        content.append(f"addLayers       {b(gs['addLayers'])};")
        content.append("")
        content.append(f"convertToMeters {gs['convertToMeters']};")
        content.append("")

        # Geometry
        content.append("geometry")
        content.append("{")
        for geo in self.geometries:
            content.append(f"    {geo['name']}")
            content.append("    {")
            content.append(f"        type {geo['type']};")
            content.append(f"        file \"{geo['file']}\";")
            if geo['regions']: # Handle named regions within STL
                content.append("        regions")
                content.append("        {")
                regions_list = [r.strip() for r in geo['regions'].split(',') if r.strip()]
                for region_item in regions_list:
                    # Assuming region_item could be "regionName { name aliasName; }" or just "regionName"
                    # For simplicity, if it contains '{', assume it's a full entry
                    if '{' in region_item and '}' in region_item:
                        content.append(f"            {region_item}") # User provides full sub-dict
                    else: # Assume it's just a name, create a simple entry
                        content.append(f"            {region_item} {{ name {region_item}; }}")
                content.append("        }")
            content.append("    }")
        content.append("};")
        content.append("")

        # CastellatedMeshControls
        cmc = self.castellated_mesh_controls
        content.append("castellatedMeshControls")
        content.append("{")
        content.append(f"    maxLocalCells               {cmc['maxLocalCells']};")
        content.append(f"    maxGlobalCells              {cmc['maxGlobalCells']};")
        content.append(f"    minRefinementCells          {cmc['minRefinementCells']};")
        content.append(f"    maxLoadUnbalance            {cmc['maxLoadUnbalance']:.2f};")
        content.append(f"    nCellsBetweenLevels         {cmc['nCellsBetweenLevels']};")
        content.append("")
        content.append(f"    locationInMesh              ({cmc['locationInMesh'][0]} {cmc['locationInMesh'][1]} {cmc['locationInMesh'][2]});")
        content.append(f"    allowFreeStandingZoneFaces  {b(cmc['allowFreeStandingZoneFaces'])};")
        content.append("")

        content.append("    features")
        content.append("    (")
        for f in cmc["features"]:
            content.append(f"        {{ file \"{f['file']}\"; level {f['level']}; }}")
        content.append("    );")
        content.append("")

        content.append("    refinementSurfaces")
        content.append("    {")
        for rs in cmc["refinementSurfaces"]:
            content.append(f"        {rs['geometry']}") # Geometry name is the key
            content.append("        {")
            content.append(f"            level ({rs['level_min']} {rs['level_max']});")
            if rs['regions']:
                content.append("            regions")
                content.append("            {")
                # Assuming regions are comma-separated simple names for now
                # e.g. "region1 { level (2 3); patchInfo { type wall; } }, region2 { level (3 3); }"
                # For the GUI, we'll keep it simpler: user types the full content for the regions sub-dict
                # This is a complex part; for now, we'll assume user puts the region details in the string.
                # A more robust GUI would have a sub-table for regions within refinementSurfaces.
                # Example: "wing { level (2 3); }"
                # If rs['regions'] is "wing { level (2 3); }", it will be printed as is.
                # For multiple, they'd be comma separated in the input field.
                # This is a simplification.
                content.append(f"                {rs['regions']} // User provided region refinement details")
                content.append("            }")
            if rs['patchInfo']: # User types the content of patchInfo, e.g. "{ type wall; }"
                content.append(f"            patchInfo {rs['patchInfo']};")
            content.append("        }")
        content.append("    }")
        content.append("")

        content.append("    refinementRegions")
        content.append("    {")
        for rr in cmc["refinementRegions"]:
            content.append(f"        {rr['geometry']}") # Geometry name is the key
            content.append("        {")
            content.append(f"            mode {rr['mode']};")
            content.append("            levels (")
            # Parse "dist1 lvl1; dist2 lvl2" into OpenFOAM list of lists
            levels_str_list = []
            for pair_str in rr['levels'].split(';'):
                pair = pair_str.strip().split()
                if len(pair) == 2:
                    levels_str_list.append(f"({pair[0]} {pair[1]})")
            content.append(f"                {' '.join(levels_str_list)}")
            content.append("            );")
            content.append("        }")
