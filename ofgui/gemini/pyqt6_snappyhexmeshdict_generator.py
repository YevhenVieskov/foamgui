        content.append(f"    nSmoothScale            {mqc['nSmoothScale']};")
        content.append(f"    errorReduction          {mqc['errorReduction']:.2f};")
        if mqc["relaxed"]["enabled"]:
            content.append("    relaxed")
            content.append("    {")
            content.append(f"        maxNonOrtho         {mqc['relaxed']['maxNonOrtho']:.1f};")
            content.append("    }")
        content.append("}")
        content.append("")

        # Advanced
        content.append(f"mergeTolerance {gs['mergeTolerance']:.1e};")
        content.append("")

        if self.debug_flags:
            content.append("debugFlags")
            content.append("(")
            content.append(f"    {format_list_of_strings(self.debug_flags)}")
            content.append(");")
            content.append("")

